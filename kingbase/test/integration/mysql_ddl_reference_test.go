package kingbase_test

import "testing"

// These optional server reference queries are not adaptation acceptance tests.
func TestKingbaseMySQLMode_NativeDDLReference(t *testing.T) {
	runMySQLDDLCases(t, "金仓官方参考：只验证服务器能力，不计 ORM 或原始 MySQL 兼容通过", []mysqlDDLTestCase{
		{"01_NativeDropIndex", "金仓参考：删除索引", mysqlDDLNativeDropIndex},
		{"11_TruncateContinueIdentity", "金仓参考：TRUNCATE 保留序列", func(c *mysqlDDLCase) { mysqlDDLTruncate(c, false) }},
		{"12_TruncateRestartIdentity", "金仓参考：TRUNCATE 重置序列", func(c *mysqlDDLCase) { mysqlDDLTruncate(c, true) }},
	})
}

func mysqlDDLNativeDropIndex(c *mysqlDDLCase) {
	table := c.table("id INTEGER PRIMARY KEY, name VARCHAR(32)")
	index := "idx_" + table
	c.prepare("CREATE INDEX " + c.quote(index) + " ON " + c.quote(table) + " (name)")
	c.indexCount("删除前索引存在", table, index, 1)
	c.statement("原生删除索引", "DROP INDEX "+c.quote(index))
	c.indexCount("删除后索引不存在", table, index, 0)
}

func mysqlDDLTruncate(c *mysqlDDLCase, restart bool) {
	table := c.table("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(32)")
	c.prepare("INSERT INTO " + c.quote(table) + " (name) VALUES ('first'), ('second')")
	var before int64
	if err := c.db.CommonDB().QueryRow("SELECT MAX(id) FROM " + c.quote(table)).Scan(&before); err != nil {
		c.t.Fatalf("[未通过] 读取清空前自增值: %v", err)
	}
	c.count("清空前两条记录", "SELECT COUNT(*) FROM "+c.quote(table), 2)
	option := "CONTINUE IDENTITY"
	if restart {
		option = "RESTART IDENTITY"
	}
	if !c.statement("清空表", "TRUNCATE TABLE "+c.quote(table)+" "+option) {
		return
	}
	c.count("清空后零条记录", "SELECT COUNT(*) FROM "+c.quote(table), 0)
	c.prepare("INSERT INTO " + c.quote(table) + " (name) VALUES ('after')")
	var after int64
	if err := c.db.CommonDB().QueryRow("SELECT id FROM " + c.quote(table) + " WHERE name = 'after'").Scan(&after); err != nil {
		c.t.Fatalf("[未通过] 读取清空后自增值: %v", err)
	}
	want := before + 1
	if restart {
		want = 1
	}
	if after != want {
		c.t.Errorf("[未通过] %s：清空前=%d；清空后=%d；预期=%d", option, before, after, want)
	} else {
		c.t.Logf("[状态通过] %s：清空后自增值=%d", option, after)
	}
}

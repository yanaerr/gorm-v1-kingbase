func TestKingbaseOracleMetadataSQL(t *testing.T) {
	for _, qualified := range []bool{false, true} {
		t.Run(strconv.FormatBool(qualified), func(t *testing.T) {
			db, mock, close := openMockGorm(t, kb.DialectKingbaseOracle)
			defer close()
			table := "Users"
			schemaPredicate := "= current_schema()"
			prefix := []driver.Value{}
			if qualified {
				table = `"APP"."Users"`
				schemaPredicate = "= ?"
				prefix = append(prefix, "APP")
			}
			cases := []struct {
				query string
				args  []driver.Value
				run   func() bool
			}{
				{"SELECT COUNT(*) FROM information_schema.tables WHERE table_schema " + schemaPredicate + " AND table_name = ?", []driver.Value{"Users"}, func() bool { return db.Dialect().HasTable(table) }},
				{"SELECT COUNT(*) FROM information_schema.columns WHERE table_schema " + schemaPredicate + " AND table_name = ? AND column_name = ?", []driver.Value{"Users", "Name"}, func() bool { return db.Dialect().HasColumn(table, `"Name"`) }},
				{"SELECT COUNT(*) FROM pg_indexes WHERE schemaname " + schemaPredicate + " AND tablename = ? AND indexname = ?", []driver.Value{"Users", "Idx"}, func() bool { return db.Dialect().HasIndex(table, `"Idx"`) }},
				{"SELECT COUNT(*) FROM information_schema.table_constraints WHERE table_schema " + schemaPredicate + " AND table_name = ? AND constraint_name = ? AND constraint_type = 'FOREIGN KEY'", []driver.Value{"Users", "Fk"}, func() bool { return db.Dialect().HasForeignKey(table, `"Fk"`) }},
			}
			for _, c := range cases {
				for _, count := range []int{1, 0} {
					mock.ExpectQuery("^" + regexp.QuoteMeta(c.query) + "$").WithArgs(append(prefix, c.args...)...).WillReturnRows(sqlmock.NewRows([]string{"count"}).AddRow(count))
					if got := c.run(); got != (count > 0) {
						t.Fatalf("metadata result=%v count=%d SQL=%s", got, count, c.query)
					}
				}
			}
			if err := mock.ExpectationsWereMet(); err != nil {
				t.Fatal(err)
			}
		})
	}
}

type oracleMetadataErrorObserver struct {
	gorm.SQLCommon
	errors []error
}

func (o *oracleMetadataErrorObserver) ReportMetadataError(err error) {
	o.errors = append(o.errors, err)
}

func TestKingbaseOracleMetadataErrorsAreReportedWithoutFallback(t *testing.T) {
	sqlDB, mock, err := sqlmock.New()
	if err != nil {
		t.Fatal(err)
	}
	defer sqlDB.Close()
	observer := &oracleMetadataErrorObserver{SQLCommon: sqlDB}
	db, err := gorm.Open(kb.DialectKingbaseOracle, observer)
	if err != nil {
		t.Fatal(err)
	}
	failure := errors.New("catalog permission denied")
	checks := []func(){
		func() {
			if db.Dialect().HasTable("users") {
				t.Fatal("failed lookup returned true")
			}
		},
		func() {
			if db.Dialect().HasColumn("users", "name") {
				t.Fatal("failed lookup returned true")
			}
		},
		func() {
			if db.Dialect().HasIndex("users", "idx") {
				t.Fatal("failed lookup returned true")
			}
		},
		func() {
			if db.Dialect().HasForeignKey("users", "fk") {
				t.Fatal("failed lookup returned true")
			}
		},
		func() {
			if db.Dialect().CurrentDatabase() != "" {
				t.Fatal("failed schema lookup returned a name")
			}
		},
	}
	for i, check := range checks {
		mock.ExpectQuery("^SELECT ").WillReturnError(failure)
		check()
		if len(observer.errors) != i+1 || observer.errors[i] != failure {
			t.Fatalf("original error lost: %v", observer.errors)
		}
	}
	if err := mock.ExpectationsWereMet(); err != nil {
		t.Fatal(err)
	}
}

func TestKingbaseOracleReturningAndDefaultBoundaries(t *testing.T) {
	dialect := kb.NewKingbaseDialect(kb.KbModeOracle)
	if got, want := dialect.LastInsertIDReturningSuffix(`"APP"."Order"`, `"id"`), `RETURNING "APP"."Order"."id"`; got != want {
		t.Fatalf("Oracle RETURNING suffix mismatch: got %q, want %q", got, want)
	}
	if got := dialect.LastInsertIDOutputInterstitial("Order", "id", nil); got != "" {
		t.Fatalf("unexpected Oracle output interstitial: %q", got)
	}
	if got, want := dialect.DefaultValueStr(), "DEFAULT VALUES"; got != want {
		t.Fatalf("Oracle default value SQL mismatch: got %q, want %q", got, want)
	}

	// A quoted identifier is kept as one identifier by the suffix method. Path
	// quoting is verified separately through the public ModifyColumn path.
	if got, want := dialect.LastInsertIDReturningSuffix("APP.Order", "id"), `RETURNING APP.Order.id`; got != want {
		t.Fatalf("unquoted RETURNING suffix mismatch: got %q, want %q", got, want)
	}
}

func TestKingbaseOracleDialectIsSelfContained(t *testing.T) {
	dialect := kb.NewKingbaseDialect(kb.KbModeOracle)

	if got := dialect.GetName(); got != kb.DialectKingbaseOracle {
		t.Fatalf("dialect name mismatch: got %q, want %q", got, kb.DialectKingbaseOracle)
	}
	if got := dialect.BindVar(1); got != "?" {
		t.Fatalf("bind variable mismatch: got %q, want %q", got, "?")
	}
	if got := dialect.SelectFromDummyTable(); got != "FROM DUAL" {
		t.Fatalf("dummy table mismatch: got %q", got)
	}
	if got := dialect.LastInsertIDOutputInterstitial("users", "id", []string{"name"}); got != "" {
		t.Fatalf("unexpected output interstitial: %q", got)
	}
	if got, want := dialect.LastInsertIDReturningSuffix(`"users"`, `"id"`), `RETURNING "users"."id"`; got != want {
		t.Fatalf("returning suffix mismatch: got %q, want %q", got, want)
	}
	if got := dialect.DefaultValueStr(); got != "DEFAULT VALUES" {
		t.Fatalf("default value SQL mismatch: got %q", got)
	}
	if got, want := dialect.BuildKeyName("idx", "users", "name"), "idx_users_name"; got != want {
		t.Fatalf("key name mismatch: got %q, want %q", got, want)
	}
	if index, column := dialect.NormalizeIndexAndColumn("idx_users_name", "name"); index != "idx_users_name" || column != "name" {
		t.Fatalf("normalized index mismatch: index=%q column=%q", index, column)
	}
	if dialect.CurrentDatabase() != "" {
		t.Fatal("dialect without DB returned a current schema")
	}
	if dialect.HasTable("users") || dialect.HasColumn("users", "name") ||
		dialect.HasIndex("users", "idx_users_name") || dialect.HasForeignKey("users", "fk_users_company") {
		t.Fatal("metadata lookup without DB unexpectedly succeeded")
	}
	if err := dialect.RemoveIndex("users", "idx_users_name"); err != sql.ErrConnDone {
		t.Fatalf("expected sql.ErrConnDone without DB, got %v", err)
	}
}


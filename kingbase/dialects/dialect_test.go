func TestKingbaseOraclePagination(t *testing.T) {
	db, _, cleanup := openMockGorm(t, DialectKingbaseOracle)
	defer cleanup()

	tests := []struct {
		name   string
		limit  interface{}
		offset interface{}
		want   string
	}{
		{name: "limit", limit: 10, want: " FETCH FIRST 10 ROWS ONLY"},
		{name: "limit and offset", limit: "10", offset: 20, want: " OFFSET 20 ROWS FETCH NEXT 10 ROWS ONLY"},
		{name: "offset", offset: 20, want: " OFFSET 20 ROWS"},
		{name: "negative values", limit: -1, offset: -1, want: ""},
		{name: "unset", want: ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := db.Dialect().LimitAndOffsetSQL(tt.limit, tt.offset)
			if err != nil {
				t.Fatalf("LimitAndOffsetSQL returned error: %v", err)
			}
			if got != tt.want {
				t.Fatalf("pagination mismatch: got %q, want %q", got, tt.want)
			}
		})
	}

	if _, err := db.Dialect().LimitAndOffsetSQL("invalid", nil); err == nil {
		t.Fatal("expected invalid limit to return an error")
	}
	if _, err := db.Dialect().LimitAndOffsetSQL(nil, "invalid"); err == nil {
		t.Fatal("expected invalid offset to return an error")
	}
}


func openMockGorm(t *testing.T, dialect string) (*gorm.DB, sqlmock.Sqlmock, func()) {
	t.Helper()
	sqlDB, mock, err := sqlmock.New()
	if err != nil {
		t.Fatalf("create sqlmock: %v", err)
	}
	db, err := gorm.Open(dialect, sqlDB)
	if err != nil {
		_ = sqlDB.Close()
		t.Fatalf("open gorm: %v", err)
	}
	return db, mock, func() {
		_ = db.Close()
	}
}

func fieldType(t *testing.T, db *gorm.DB, model interface{}, name string) string {
	t.Helper()
	for _, field := range db.NewScope(model).GetModelStruct().StructFields {
		if field.Name == name {
			return strings.ToLower(db.Dialect().DataTypeOf(field))
		}
	}
	t.Fatalf("field %s not found", name)
	return ""
}

func TestKingbaseOracleTypeMapping(t *testing.T) {
	db, _, cleanup := openMockGorm(t, DialectKingbaseOracle)
	defer cleanup()

	assertType := func(field, want string) {
		t.Helper()
		if got := fieldType(t, db, &oracleTypeModel{}, field); got != strings.ToLower(want) {
			t.Fatalf("%s type mismatch: got %q, want %q", field, got, want)
		}
	}

	assertType("ID", "integer generated by default as identity")
	assertType("Name", "varchar2(64) NOT NULL")
	assertType("Note", "clob")
	assertType("Price", "number(10,2) NOT NULL")
	assertType("Payload", "blob")
	assertType("Active", "boolean NOT NULL DEFAULT true")
	assertType("CreatedAt", "timestamp with time zone")
}


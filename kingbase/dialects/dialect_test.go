func TestKingbaseOracleMetadataSQL(t *testing.T) {
	db, mock, cleanup := openMockGorm(t, DialectKingbaseOracle)
	defer cleanup()

	expectCount := func(query string, args ...driver.Value) {
		t.Helper()
		mock.ExpectQuery(regexp.QuoteMeta(query)).
			WithArgs(args...).
			WillReturnRows(sqlmock.NewRows([]string{"count"}).AddRow(1))
	}

	expectCount("SELECT COUNT(*) FROM user_tables WHERE LOWER(table_name) = LOWER(?)", "users")
	if !db.Dialect().HasTable("users") {
		t.Fatal("expected oracle HasTable to use user_tables")
	}

	expectCount("SELECT COUNT(*) FROM user_tab_columns WHERE LOWER(table_name) = LOWER(?) AND LOWER(column_name) = LOWER(?)", "users", "name")
	if !db.Dialect().HasColumn("users", "name") {
		t.Fatal("expected oracle HasColumn to use user_tab_columns")
	}

	expectCount("SELECT COUNT(*) FROM user_indexes WHERE LOWER(table_name) = LOWER(?) AND LOWER(index_name) = LOWER(?)", "users", "idx_users_name")
	if !db.Dialect().HasIndex("users", "idx_users_name") {
		t.Fatal("expected oracle HasIndex to use user_indexes")
	}

	expectCount("SELECT COUNT(*) FROM user_constraints WHERE LOWER(table_name) = LOWER(?) AND LOWER(constraint_name) = LOWER(?) AND constraint_type = 'R'", "users", "fk_users_company")
	if !db.Dialect().HasForeignKey("users", "fk_users_company") {
		t.Fatal("expected oracle HasForeignKey to use user_constraints")
	}

	if err := mock.ExpectationsWereMet(); err != nil {
		t.Fatalf("sql expectations: %v", err)
	}
}


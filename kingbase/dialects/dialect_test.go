func TestKingbaseRawDialectIsConnectionScoped(t *testing.T) {
	db1, _, cleanup1 := openMockGorm(t, DialectKingbaseMySQL)
	defer cleanup1()
	db2, _, cleanup2 := openMockGorm(t, DialectKingbaseMySQL)
	defer cleanup2()

	dialect1, ok := db1.Dialect().(*kingbaseMySQLDialect)
	if !ok {
		t.Fatalf("unexpected first dialect type: %T", db1.Dialect())
	}
	dialect2, ok := db2.Dialect().(*kingbaseMySQLDialect)
	if !ok {
		t.Fatalf("unexpected second dialect type: %T", db2.Dialect())
	}
	if dialect1.raw == nil || dialect2.raw == nil {
		t.Fatal("raw dialect was not initialized")
	}
	if dialect1.raw == dialect2.raw {
		t.Fatal("raw dialect instances are shared between connections")
	}
}


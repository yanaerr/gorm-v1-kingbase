func TestKingbaseOracleSchemaMetadataFallsBackWhenOracleCatalogIsEmpty(t *testing.T) {
	db, mock, cleanup := openMockGorm(t, DialectKingbaseOracle)
	defer cleanup()

	expectZero := func(query string, args ...driver.Value) {
		t.Helper()
		mock.ExpectQuery(regexp.QuoteMeta(query)).
			WithArgs(args...).
			WillReturnRows(sqlmock.NewRows([]string{"count"}).AddRow(0))
	}
	expectOne := func(query string, args ...driver.Value) {
		t.Helper()
		mock.ExpectQuery(regexp.QuoteMeta(query)).
			WithArgs(args...).
			WillReturnRows(sqlmock.NewRows([]string{"count"}).AddRow(1))
	}

	expectZero("SELECT COUNT(*) FROM all_tables WHERE LOWER(owner) = LOWER(?) AND LOWER(table_name) = LOWER(?)", "public", "users")
	expectOne("SELECT COUNT(*) FROM information_schema.tables WHERE LOWER(table_schema) = LOWER(?) AND LOWER(table_name) = LOWER(?)", "public", "users")
	if !db.Dialect().HasTable("public.users") {
		t.Fatal("expected schema-qualified HasTable to fall back when all_tables is empty")
	}

	expectZero("SELECT COUNT(*) FROM all_tab_columns WHERE LOWER(owner) = LOWER(?) AND LOWER(table_name) = LOWER(?) AND LOWER(column_name) = LOWER(?)", "public", "users", "name")
	expectOne("SELECT COUNT(*) FROM information_schema.columns WHERE LOWER(table_schema) = LOWER(?) AND LOWER(table_name) = LOWER(?) AND LOWER(column_name) = LOWER(?)", "public", "users", "name")
	if !db.Dialect().HasColumn("public.users", "name") {
		t.Fatal("expected schema-qualified HasColumn to fall back when all_tab_columns is empty")
	}

	expectZero("SELECT COUNT(*) FROM all_indexes WHERE LOWER(owner) = LOWER(?) AND LOWER(table_name) = LOWER(?) AND LOWER(index_name) = LOWER(?)", "public", "users", "idx_users_name")
	expectOne("SELECT COUNT(*) FROM pg_indexes WHERE LOWER(schemaname) = LOWER(?) AND LOWER(tablename) = LOWER(?) AND LOWER(indexname) = LOWER(?)", "public", "users", "idx_users_name")
	if !db.Dialect().HasIndex("public.users", "idx_users_name") {
		t.Fatal("expected schema-qualified HasIndex to fall back when all_indexes is empty")
	}

	expectZero("SELECT COUNT(*) FROM all_constraints WHERE LOWER(owner) = LOWER(?) AND LOWER(table_name) = LOWER(?) AND LOWER(constraint_name) = LOWER(?) AND constraint_type = 'R'", "public", "users", "fk_users_company")
	expectOne("SELECT COUNT(*) FROM information_schema.table_constraints WHERE LOWER(table_schema) = LOWER(?) AND LOWER(table_name) = LOWER(?) AND LOWER(constraint_name) = LOWER(?) AND constraint_type = 'FOREIGN KEY'", "public", "users", "fk_users_company")
	if !db.Dialect().HasForeignKey("public.users", "fk_users_company") {
		t.Fatal("expected schema-qualified HasForeignKey to fall back when all_constraints is empty")
	}

	if err := mock.ExpectationsWereMet(); err != nil {
		t.Fatalf("sql expectations: %v", err)
	}
}
